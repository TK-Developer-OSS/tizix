;===================================================================
; ovlvec.s - オーバーレイ → core 呼び出しベクタ (tizix #36 続き)
;
;   #37 で vi のオーバーレイ化が失敗した理由は「オーバーレイから親(core)の
;   関数を呼べない」ことだった。呼べないので、切り出したコードが使うヘルパーを
;   オーバーレイ側が全部抱え込む ── 実測で core が 639B しか減らないのに
;   オーバーレイが 2672B かかった。これを解く。
;
;   ■ なぜ固定番地の表なのか
;     tzcc は関数ポインタを生成できない(readme.md: 全て call _name の静的
;     リンク解決)。よって親が C で「&helper を表に書き込む」ことはできない。
;     代わりに **リンカに解決させたサンクを固定番地へ置く**。実行時の
;     書き換えは不要。
;
;     `-g sym=val` で core のアドレスをオーバーレイへ渡す手もあるが、
;     core が 1 バイト動くたびに全オーバーレイを貼り直すことになる。
;     固定番地なら ABI が安定し、オーバーレイを独立に作れる。
;
;   ■ 配置: **オーバーレイ領域の直下**(OVLADDR - 24)へ置く。
;     「表は自分のロード番地の 24 バイト下」という不変のルールになるので、
;     OVLADDR を動かしても両側の取り決めが壊れない(TK 案「親のジャンプ命令を
;     後端に置く」)。リンク時は -b _OVLVEC=<OVLADDR-24> で番地を与える。
;
;     なお Z80 に **相対 CALL は無い**(jr/djnz のみ、±128B)。オーバーレイ内の
;     呼び出し箇所は全体に散るので、相対分岐だけでは core へ届かない。よって
;     サンクで IY を足す形は残す。
;     +0  サンク 8B  … IY を足して core の _ovl_svc へ飛ぶ
;     +8  引数ブロック … core とオーバーレイが peekw/pokew で共有する。
;                        callovl() は引数を 1 個しか渡せないので、2 個目以降は
;                        ここへ置く。番地は両側で **決め打ち**(シンボル共有なし)。
;
;   ■ 呼び出し規約
;     overlay:  pokew(base+OVLVEC+8, a); pokew(base+OVLVEC+10, b);
;               rc = callovl(base+OVLVEC, SEL_xxx);
;     core   :  int ovl_svc(int sel) { ... peekw(OVLVEC+8) ... }
;
;   手書きなので tzcc の IY 変換は掛からない。IY の加算はここで明示的に行う。
;===================================================================

        .module ovlvec
        .globl  _ovl_svc

        .area   _OVLVEC

        ld      hl, #_ovl_svc   ; リンク時オフセット(core 内)
        push    iy
        pop     de
        add     hl, de          ; HL = IY + オフセット = 実アドレス
        jp      (hl)            ; 戻り番地はそのまま = _ovl_svc の ret で呼出元へ

        .ds     16              ; +8: 引数ブロック(16B)
