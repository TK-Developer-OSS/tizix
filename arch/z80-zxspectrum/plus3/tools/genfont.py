#!/usr/bin/env python3
"""genfont.py TI84_CONSOLE.C > font.inc : turn the 5x7 column font of arch/z80-ti84plus/console.c (95 glyphs, 5 columns,
bit 0 = top row) into 8x8 row glyphs for the Spectrum: byte r = row r, bit 6 = leftmost pixel (bit 7 stays blank).
The output is committed as font.inc; this script is only needed to regenerate it."""
import re, sys
src = open(sys.argv[1]).read()
m = re.search(r"font\[95 \* 5\] = \{(.*?)\};", src, re.S)
body = re.sub(r"/\*.*?\*/", "", m.group(1))
cols = [int(x, 16) for x in re.findall(r"0x[0-9A-Fa-f]+", body)]
assert len(cols) == 95 * 5
print("; ASCII 0x20-0x7F, 8 bytes a glyph (row 0 first), pixels in bits 6..2 (generated by tools/genfont.py)")
for g in range(96):
    if g < 95:
        c = cols[g * 5:g * 5 + 5]
        rows = [sum(((c[x] >> r) & 1) << (6 - x) for x in range(5)) for r in range(8)]
    else:
        rows = [0] * 8
    print("        .db     " + ", ".join("0x%02X" % v for v in rows) + "  ; 0x%02X" % (0x20 + g))
