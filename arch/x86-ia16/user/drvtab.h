/* arch/x86-ia16/user/drvtab.h : the DRIVER's function table, in index order (one line per index, no gaps).
 *   The numbers follow the z80 drv_tbl (user/stdio.h, user/shvec.h): 0 putchar, 1 getchar, 2 printf, 3 fopen, ...
 *   27..45 are the z80 sh's kernel entries; the ia16 sh calls the kernel by syscall, so they are holes here.
 *   64.. are ia16 additions (the string functions every command used to carry, and prs / prnum).
 *   Read by user/drvc.S (one stub per DRV in every command) and tz/drv16e.S (the table at the head of driver.bin),
 *   so the two sides cannot disagree.
 *     DRV(n, name)  index n is name
 *     DRVZ(n, name) index n is name, but it has nothing to do here: commands get the stub, the DRIVER's entry
 *                   is the common "return 0" (fflush has no buffer to flush, proc_block / proc_wake are no-ops)
 *     DRVX(n)       index n is not provided (the driver returns 0)
 */
